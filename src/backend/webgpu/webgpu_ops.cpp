// WebGPU backend: host side over webgpu.h. The same source builds natively against Dawn and in the
// browser against Emscripten's emdawnwebgpu. The kernels are in kernels.wgsl, compiled at run time.
// The context (batching, uniform ring, error scopes, read-back) follows just-keypoints' WebGPU backend.
//
// Every tensor is its own storage buffer. Dispatches are encoded into one compute pass and submitted when
// the host needs a value (Tensor::read), writes a buffer, or calls flush: a write is queued after
// everything submitted before it, so flushing first keeps host writes in program order, and a buffer
// returned to the pool can be reused at once (dispatches run in order).
//
// Scalar arguments go into a ring of 256-byte uniform slots, one per dispatch, written just before the
// submission. Each dispatch gets its own bind group: binding 0 is its slot, buffers follow in the order
// they are passed.
//
// Precision: FP16 needs the shader-f16 feature: tensors and weights are stored as f16, arithmetic is f32.
// The logits of the read-out and its results are f32 in both modes. WGSL cannot turn off contraction into
// fused multiply-adds, so FP32 results differ from the CPU backend in the last bits.
//
// Environment: JMT_WEBGPU_DUMP=DIR writes every kernel module to DIR (debugging aid). JMT_WEBGPU_PROFILE=1
// waits for every dispatch and prints the wall time per kernel when the backend is destroyed (includes
// a round trip per dispatch; for the shares, not the totals).

  TensorPtr rotary(const TensorPtr& xp, const std::vector<float>& cos, const std::vector<float>& sin, int heads) override {
    const MetalTensor& x = dev(xp);
    const int pairs = x.c / heads / 2;
    if (static_cast<int>(cos.size()) != x.n() * pairs) fail("rotary: shape mismatch");
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, x.c);
    ctx_->tag("rotary");
    ctx_->run("k_rotary", static_cast<long long>(x.n()) * heads * pairs, x.d(), ctx_->table(cos), ctx_->table(sin), x.n(), heads, pairs,
              out->d());
    return out;
  }

  TensorPtr rotary_keypoints(const TensorPtr& xp, const TensorPtr& cosp, const TensorPtr& sinp, int heads) override {
    const MetalTensor &x = dev(xp), &c = dev(cosp), &sn = dev(sinp);
    const int pairs = x.c / heads / 2;
    if (c.n() != x.n() || c.c != pairs || sn.n() != x.n() || sn.c != pairs || c.half != x.half || sn.half != x.half)
      fail("rotary_keypoints: shape mismatch");
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, x.c);
    ctx_->tag("rotary");
    ctx_->run("k_rotary_t", static_cast<long long>(x.n()) * heads * pairs, x.d(), c.d(), sn.d(), x.n(), heads, pairs, out->d());
    return out;
  }

  TensorPtr gather_rows(const TensorPtr& xp, const std::vector<int>& rows) override {
    const MetalTensor& x = dev(xp);
    const int count = static_cast<int>(rows.size());
    for (int r : rows)
      if (r < 0 || r >= x.n()) fail("gather_rows: index out of range");
    auto out = std::make_shared<MetalTensor>(ctx_, 1, count, x.c);
    if (count == 0) return out;
    Buffer idx(ctx_, rows.size() * sizeof(int), true);
    std::memcpy(idx.host(), rows.data(), rows.size() * sizeof(int));
    ctx_->tag("gather");
    ctx_->run("k_gather_rows", static_cast<long long>(count) * x.c, x.d(), idx.view(), x.c, count, out->d());
    return out;
  }

  // The similarity is the read-out's product (float in both precisions); the rest is four small passes.
  void assignment(const TensorPtr& ap, const TensorPtr& bp, const TensorPtr& zap, const TensorPtr& zbp,
                  std::vector<int>* best0, std::vector<float>* max0, std::vector<int>* best1,
                  std::vector<float>* max1) override {
    const MetalTensor &a = dev(ap), &b = dev(bp), &za = dev(zap), &zb = dev(zbp);
    const int M = a.n(), N = b.n();
    if (a.c != b.c || za.n() != M || zb.n() != N || za.c != 1 || zb.c != 1) fail("assignment: shape mismatch");
    best0->assign(M, -1), max0->assign(M, -INFINITY), best1->assign(N, -1), max1->assign(N, -INFINITY);
    if (M == 0 || N == 0) return;
    TensorPtr s = readout_logits(ap, bp, 1.0f / std::sqrt(static_cast<float>(a.c)));
    auto f32 = [&](int n) { return std::make_shared<MetalTensor>(ctx_, 1, n, 1, false, true); };
    auto row_lse = f32(M), col_lse = f32(N), arg0 = f32(M), val0 = f32(M), arg1 = f32(N), val1 = f32(N);
    ctx_->tag(format("assignment M %d N %d", M, N));
    ctx_->run_groups("k_lse_rows", M, 32, dev(s).d(), N, row_lse->d());
    ctx_->run("k_lse_cols", N, dev(s).d(), M, N, col_lse->d());
    ctx_->run_groups("k_best_rows", M, 32, dev(s).d(), N, row_lse->d(), col_lse->d(), za.d(), zb.d(), arg0->d(), val0->d());
    ctx_->run("k_best_cols", N, dev(s).d(), M, N, row_lse->d(), col_lse->d(), za.d(), zb.d(), arg1->d(), val1->d());
    std::vector<float> idx0(M), idx1(N);
    arg0->read(idx0.data()), val0->read(max0->data()), arg1->read(idx1.data()), val1->read(max1->data());
    for (int i = 0; i < M; ++i) (*best0)[i] = static_cast<int>(idx0[i]);
    for (int j = 0; j < N; ++j) (*best1)[j] = static_cast<int>(idx1[j]);
  }

  TensorPtr attention(const TensorPtr& qp, const TensorPtr& kp, const TensorPtr& vp, int heads) override {
    const MetalTensor &q = dev(qp), &k = dev(kp), &v = dev(vp);
    if (q.c != heads * 64 || k.c != q.c || v.c != q.c || k.n() != v.n()) fail("attention: needs 64 channels per head");
    auto out = std::make_shared<MetalTensor>(ctx_, q.h, q.w, q.c);
    const int P = q.n(), S = k.n(), spad = (S + 7) / 8 * 8;
    if (ctx_->mpp()) {
      ctx_->tag(format("attention P %d S %d", P, S));
      ctx_->run_groups("k_attn", static_cast<long long>(heads) * ((P + 31) / 32), 32, q.d(), k.d(), v.d(), P, S, heads, out->d());
      return out;
    }
    if (spad / 8 > 1024) fail("attention: more than 8192 tokens per image (input size above 720 px)");
    // Queries are processed in chunks, so the weights buffer (heads x chunk x S) is written and read while
    // it is still in the GPU's cache.
    int chunk = attention_chunk_ > 0 ? attention_chunk_ : P;
    chunk = std::min(P, (chunk + 3) / 4 * 4);
    Buffer weights(ctx_, static_cast<size_t>(heads) * chunk * S * ctx_->elem());
    Buffer inv(ctx_, static_cast<size_t>(heads) * chunk * sizeof(float));
    Buffer keys(ctx_, static_cast<size_t>(heads) * 64 * spad * ctx_->elem());
    ctx_->tag(format("attention P %d S %d", P, S));
    ctx_->run("k_attn_keys", static_cast<long long>(heads) * 64 * spad, k.d(), S, heads, spad, keys.view());
    for (int p0 = 0; p0 < P; p0 += chunk) {
      const int pc = std::min(chunk, P - p0);
      ctx_->run_groups("k_attn_weights", static_cast<long long>(heads) * ((pc + 3) / 4), spad / 8, q.d(), keys.view(), pc, S,
                       heads, spad, weights.view(), inv.view(), p0);
      ctx_->run(format("k_attn_apply_r%d_t%d", apply_rows_, apply_tile_),
                static_cast<long long>(heads) * ((pc + apply_rows_ - 1) / apply_rows_) * (64 / apply_tile_), weights.view(),
                v.d(), pc, S, heads, inv.view(), out->d(), p0);
    }
    return out;
  }

  TensorPtr sample(const TensorPtr& xp, const float* pts, int n) override {
    const MetalTensor& x = dev(xp);
    Buffer p(ctx_, static_cast<size_t>(n) * 2 * sizeof(float), true);
    std::memcpy(p.host(), pts, static_cast<size_t>(n) * 2 * sizeof(float));
    auto out = std::make_shared<MetalTensor>(ctx_, 1, n, x.c);
    ctx_->tag("sample");
    ctx_->run("k_sample", static_cast<long long>(n) * x.c, x.d(), p.view(), x.h, x.w, x.c, n, out->d());
    return out;
  }

  void readout(const TensorPtr& queryp, const TensorPtr& searchp, float temperature, std::vector<float>* coarse,
               std::vector<float>* mass) override {
    const MetalTensor& search = dev(searchp);
    const int N = queryp->n(), P = search.n(), h = search.h, w = search.w;
    TensorPtr logits_t = readout_logits(queryp, searchp, temperature);
    std::vector<float> logits(static_cast<size_t>(N) * P);
    logits_t->read(logits.data());
    coarse->assign(static_cast<size_t>(N) * 2, 0.0f);
    mass->assign(N, 0.0f);
    const int parts = std::min(threads_, std::max(1, N));
    std::vector<std::thread> pool;
    for (int t = 0; t < parts; ++t)
      pool.emplace_back([&, t] {
        ReadoutScratch scratch;
        const int begin = static_cast<int>(static_cast<long long>(N) * t / parts);
        const int end = static_cast<int>(static_cast<long long>(N) * (t + 1) / parts);
        for (int i = begin; i < end; ++i)
          readout_row(logits.data() + static_cast<size_t>(i) * P, h, w, scratch, coarse->data() + 2 * static_cast<size_t>(i),
                      mass->data() + i);
      });
    for (auto& th : pool) th.join();
  }

  bool has_device_readout() const override { return ctx_->mpp(); }

  void readout_device(const TensorPtr& queryp, const TensorPtr& searchp, float temperature, TensorPtr* coarse,
                      TensorPtr* mass) override {
    const int N = queryp->n(), h = searchp->h, w = searchp->w;
    TensorPtr logits = readout_logits(queryp, searchp, temperature);
    auto c = std::make_shared<MetalTensor>(ctx_, 1, N, 2, false, true), m = std::make_shared<MetalTensor>(ctx_, 1, N, 1, false, true);
    ctx_->run_groups("k_readout", N, 32, dev(logits).d(), h, w, c->d(), m->d());
    *coarse = c, *mass = m;
  }

  TensorPtr sample_at(const TensorPtr& xp, const TensorPtr& ptsp) override {
    const MetalTensor &x = dev(xp), &pts = dev(ptsp);
    if (pts.half || pts.c != 2) fail("sample_at: points must be a float tensor of pairs");
    const int n = pts.n();
    auto out = std::make_shared<MetalTensor>(ctx_, 1, n, x.c);
    ctx_->tag("sample");
    ctx_->run("k_sample", static_cast<long long>(n) * x.c, x.d(), pts.d(), x.h, x.w, x.c, n, out->d());
    return out;
  }

  long device_allocations() const override { return ctx_->buffers_created(); }
  void flush() override { ctx_->flush(); }
  void finish() override { ctx_->sync(); }

 private:
  static int padded(int out_c, int tile) { return (out_c + tile - 1) / tile * tile; }
  // Position of weight (output o, input i) in the layout of k_linear.
  size_t slot(int o, int i, int in_c) const {
    return (static_cast<size_t>(o / linear_tile_) * in_c + i) * linear_tile_ + o % linear_tile_;
  }

  enum : int { kAsStored = -2, kPatchOrder = -3 };  // arrangements of a weight tensor on the device

  // A weight matrix as it is stored, (out, in), in the storage type.
  View stored(const Param& p) {
    return ctx_->param(p, kAsStored, p.size(), [&](float* dst) { std::memcpy(dst, p.data, p.size() * sizeof(float)); });
  }

  // out (h * w, out_c) = act(x (h * w, in_c) W^T + bias) + residual, with W (out_c, in_c).
  TensorPtr mm(View x, int h, int w, int in_c, View weights, const Param* bias, int out_c, Act act, const TensorPtr& residual) {
    auto out = std::make_shared<MetalTensor>(ctx_, h, w, out_c);
    const int n = h * w, flags = (bias ? 1 : 0) | (residual ? 2 : 0);
    ctx_->run_groups2("k_mm", (out_c + 63) / 64, (n + 63) / 64, 128, x, weights, bias ? vec(*bias) : weights,
                      residual ? dev(residual).d() : weights, n, in_c, out_c, flags, act_code(act), 1.0f, out->d());
    return out;
  }

  // Logits of the read-out, float (N, P) = temperature * query * search^T, with the search tokens as the
  // weights of a product. Always the plain kernel: its output is float in both precisions.
  TensorPtr readout_logits(const TensorPtr& queryp, const TensorPtr& searchp, float temperature) {
    const MetalTensor &query = dev(queryp), &search = dev(searchp);
    const int N = query.n(), P = search.n(), d = query.c;
    const int rpad = padded(P, 8);  // the read-out product always runs 4 tokens x 8 cells per thread
    Buffer weights(ctx_, static_cast<size_t>(d) * rpad * ctx_->elem());
    ctx_->tag(format("readout N %d P %d", N, P));
    ctx_->run("k_as_weights", static_cast<long long>(d) * rpad, search.d(), P, d, rpad, 8, weights.view());
    return product(ctx_->fp16() ? "k_linear_f32" : "k_linear_r4_t8", 4, 8, query.d(), 1, N, d, weights.view(), nullptr, P, temperature,
                   true);
  }

  // A vector parameter (bias, gain) in the storage type.
  View vec(const Param& p) {
    return ctx_->param(p, -1, p.size(), [&](float* dst) { std::memcpy(dst, p.data, p.size() * sizeof(float)); });
  }

  // out (h * w, out_c) = scale * x (h * w, in_c) * W + bias, W in the layout of k_linear.
  TensorPtr product(const std::string& kernel, int R, int T, View x, int h, int w, int in_c, View weights,
                    const Param* bias, int out_c, float scale, bool f32) {
    if (in_c % 4 != 0) fail("product: the number of input channels must be a multiple of 4");
    auto out = std::make_shared<MetalTensor>(ctx_, h, w, out_c, false, f32);
    const int n = h * w;
    const long long grid = static_cast<long long>((n + R - 1) / R) * ((out_c + T - 1) / T);
    ctx_->run(kernel, grid, x, weights, bias ? vec(*bias) : weights, bias ? 1 : 0, n, in_c, out_c, scale, out->d());
    return out;
  }

  TensorPtr unary(const TensorPtr& xp, int op, const char* name) {
    const MetalTensor& x = dev(xp);
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, x.c);
    ctx_->tag(name);
    ctx_->run("k_unary", checked(x.size()), x.d(), checked(x.size()), op, out->d());
    return out;
  }

  ContextPtr ctx_;
  std::string linear_kernel_;
  int linear_rows_ = 4, linear_tile_ = 8, threads_ = 1;
  int apply_rows_ = 2, apply_tile_ = 16, attention_chunk_ = 0;
};


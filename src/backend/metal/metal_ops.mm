enum : int { kGelu = 0, kRelu = 1, kNone = 2 };

int act_code(Act a) { return a == Act::Gelu ? kGelu : a == Act::Relu ? kRelu : kNone; }

[[noreturn]] void fail(const std::string& what) { throw std::runtime_error("metal: " + what); }

std::string format(const char* fmt, ...) {
  char buf[160];
  va_list args;
  va_start(args, fmt);
  std::vsnprintf(buf, sizeof(buf), fmt, args);
  va_end(args);
  return buf;
}

std::string describe_error(NSError* error) {
  return error ? std::string([[error localizedDescription] UTF8String]) : std::string("unknown error");
}

// Three floats bound as a float3 (16 bytes).
struct Float3 {
  float v[4];
};

// A buffer bound to a kernel argument.
struct View {
  id<MTLBuffer> buffer;
};

// Device, queue, compiled kernels, the open command buffer and the buffer pool. Shared by the backend
// and every tensor it created, so a tensor can wait for the work that computes it before it is read.
//
// Buffers released while work is queued or running go to `pending_`: later dispatches may reuse them at
// once, because the GPU runs dispatches in the order they were encoded, but the host may not write them.
// They become `free_` when everything submitted has completed.
class Context {
 public:
  Context(int index, bool fp16) : fp16_(fp16) {
    const char* env = std::getenv("JMT_METAL_PROFILE");
    profile_ = env && *env && std::string(env) != "0";
    @autoreleasepool {
      NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
      if (devices.count == 0) fail("no Metal device found");
      if (index < 0 || index >= static_cast<int>(devices.count)) fail("device " + std::to_string(index) + " not found");
      device_ = devices[index];
      queue_ = [device_ newCommandQueue];
      if (!queue_) fail("cannot create a command queue");
      const char* no_mpp = std::getenv("JMT_METAL_MPP");
      if (!(no_mpp && std::string(no_mpp) == "0")) mpp_ = compile(true);
      if (!mpp_ && !compile(false)) fail("shader compilation failed: " + error_);
    }
  }

  // True when the kernels built on Metal Performance Primitives are in use.
  bool mpp() const { return mpp_; }

  ~Context() {
    try {
      sync();
    } catch (...) {
    }
    if (profile_) report();
  }

  void tag(std::string t) {
    if (profile_) tag_ = std::move(t);
  }

  long buffers_created() const { return buffers_created_; }

  // Encodes `name` over n threads (1-D grid). Arguments bind to buffer indices 0, 1, ... in order:
  // a View binds a buffer, an int or float is copied with setBytes.
  template <typename... Args>
  void run(const std::string& name, long long n, const Args&... args) {
    if (n <= 0) return;
    if (n > UINT_MAX) fail("grid too large");
    @autoreleasepool {
      id<MTLComputePipelineState> pipeline = this->pipeline(name);
      id<MTLComputeCommandEncoder> enc = encoder();
      [enc setComputePipelineState:pipeline];
      NSUInteger index = 0;
      (bind(enc, index++, args), ...);
      NSUInteger group = std::min<NSUInteger>(256, pipeline.maxTotalThreadsPerThreadgroup);
      [enc dispatchThreads:MTLSizeMake(static_cast<NSUInteger>(n), 1, 1) threadsPerThreadgroup:MTLSizeMake(group, 1, 1)];
    }
    if (profile_) {
      key_ = tag_.empty() ? name : tag_ + "  " + name;
      sync();
    }
  }

  // As run, over `groups` threadgroups of exactly `group_size` threads each (kernels that reduce within
  // a threadgroup).
  template <typename... Args>
  void run_groups(const std::string& name, long long groups, int group_size, const Args&... args) {
    run_groups2(name, groups, 1, group_size, args...);
  }

  // As run_groups, over a grid of groups_x by groups_y threadgroups.
  template <typename... Args>
  void run_groups2(const std::string& name, long long groups, long long groups_y, int group_size, const Args&... args) {
    if (groups <= 0 || groups_y <= 0) return;
    if (groups > UINT_MAX || groups_y > UINT_MAX) fail("grid too large");
    @autoreleasepool {
      id<MTLComputePipelineState> pipeline = this->pipeline(name);
      if (static_cast<NSUInteger>(group_size) > pipeline.maxTotalThreadsPerThreadgroup) fail(name + ": threadgroup too large");
      id<MTLComputeCommandEncoder> enc = encoder();
      [enc setComputePipelineState:pipeline];
      NSUInteger index = 0;
      (bind(enc, index++, args), ...);
      [enc dispatchThreadgroups:MTLSizeMake(static_cast<NSUInteger>(groups), static_cast<NSUInteger>(groups_y), 1)
          threadsPerThreadgroup:MTLSizeMake(static_cast<NSUInteger>(group_size), 1, 1)];
    }
    if (profile_) {
      key_ = tag_.empty() ? name : tag_ + "  " + name;
      sync();
    }
  }

  // Commits the open command buffer without waiting for it, so the GPU works while the host goes on.
  void flush() {
    if (!command_) return;
    [encoder_ endEncoding];
    [command_ commit];
    submitted_.push_back(command_);
    command_ = nil;
    encoder_ = nil;
    ++epoch_;
  }

  // Number of the open (or next) command buffer. A tensor remembers the one that computes it.
  long epoch() const { return epoch_; }

  // Waits until the command buffers up to number `epoch` have completed: the tensors they computed can
  // then be read on the host.
  void wait(long epoch) {
    if (epoch >= epoch_) flush();
    epoch = std::min(epoch, epoch_ - 1);
    if (epoch < base_) return;
    id<MTLCommandBuffer> command = submitted_[static_cast<size_t>(epoch - base_)];
    [command waitUntilCompleted];
    for (long e = checked_; e <= epoch; ++e) {
      id<MTLCommandBuffer> c = submitted_[static_cast<size_t>(e - base_)];
      if (c.status == MTLCommandBufferStatusError) fail("command buffer failed: " + describe_error(c.error));
    }
    checked_ = std::max(checked_, epoch + 1);
    if (profile_ && !key_.empty()) {
      Stat& st = stats_[key_];
      st.ms += (command.GPUEndTime - command.GPUStartTime) * 1e3;
      ++st.calls;
      key_.clear();
    }
    if (epoch == epoch_ - 1 && !command_) {  // nothing is running: every released buffer is idle
      free_.insert(pending_.begin(), pending_.end());
      pending_.clear();
      submitted_.clear();
      base_ = checked_ = epoch_;
    }
  }

  // Commits the open command buffer and waits for everything. Afterwards the host may read and write
  // any buffer.
  void sync() {
    flush();
    wait(epoch_ - 1);
  }

  // Pool of shared-storage buffers, reused by size. `host`: the caller writes the buffer from the host
  // before the GPU uses it, so it must not be in use by the open command buffer. Otherwise a buffer that
  // was released during the open command buffer can be reused at once: dispatches run in order.
  id<MTLBuffer> alloc(size_t bytes, bool host) {
    bytes = std::max<size_t>(bytes, 16);
    if (!host) {
      auto it = pending_.find(bytes);
      if (it != pending_.end()) {
        id<MTLBuffer> b = it->second;
        pending_.erase(it);
        return b;
      }
    }
    auto it = free_.find(bytes);
    if (it != free_.end()) {
      id<MTLBuffer> b = it->second;
      free_.erase(it);
      return b;
    }
    if (bytes > device_.maxBufferLength) fail("buffer of " + std::to_string(bytes) + " bytes exceeds the device limit");
    ++buffers_created_;
    id<MTLBuffer> b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
    if (!b) {
      free_.clear();
      b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
      if (!b) fail("out of memory allocating " + std::to_string(bytes) + " bytes");
    }
    return b;
  }
  void release(id<MTLBuffer> b, size_t bytes) {
    (command_ || !submitted_.empty() ? pending_ : free_).emplace(std::max<size_t>(bytes, 16), b);
  }

  bool fp16() const { return fp16_; }
  size_t elem() const { return fp16_ ? sizeof(uint16_t) : sizeof(float); }

  // Device copy of a weight tensor rearranged by `fill(dst)` into n values, made on first use and kept.
  // Weights outlive the backend (see jmt_ctx). `kind` separates different arrangements of one tensor.
  template <typename Fill>
  View param(const Param& p, int kind, size_t n, Fill fill) {
    auto key = std::make_pair(p.data, kind);
    auto it = params_.find(key);
    if (it != params_.end()) return {it->second};
    std::vector<float> values(n, 0.0f);
    fill(values.data());
    id<MTLBuffer> b = [device_ newBufferWithLength:std::max<size_t>(n * elem(), 16) options:MTLResourceStorageModeShared];
    if (!b) fail("out of memory for weights");
    store(values.data(), n, [b contents]);
    params_[key] = b;
    return {b};
  }

  // Device copy of a table of floats, kept as float and keyed by its address: for tables that the caller
  // keeps unchanged for its lifetime (the rotary angles).
  View table(const std::vector<float>& values) {
    auto key = std::make_pair(values.data(), static_cast<int>(values.size()));
    auto it = params_.find(key);
    if (it != params_.end()) return {it->second};
    id<MTLBuffer> b = [device_ newBufferWithLength:std::max<size_t>(values.size() * sizeof(float), 16) options:MTLResourceStorageModeShared];
    if (!b) fail("out of memory for a table");
    std::memcpy([b contents], values.data(), values.size() * sizeof(float));
    params_[key] = b;
    return {b};
  }

  // Host floats -> the storage type.
  void store(const float* src, size_t n, void* dst) const {
    if (fp16_) {
      uint16_t* d = static_cast<uint16_t*>(dst);
      for (size_t i = 0; i < n; ++i) d[i] = float_to_half(src[i]);
    } else if (n) {
      std::memcpy(dst, src, n * sizeof(float));
    }
  }

 private:
  struct Stat {
    double ms = 0;
    long calls = 0;
  };

  // Compiles the kernels, with or without the Metal Performance Primitives section. With it, also builds
  // its pipelines, so that a system that cannot run them is found out here and not in the first match.
  bool compile(bool mpp) {
    MTLCompileOptions* options = [[MTLCompileOptions alloc] init];
    NSMutableDictionary* macros = [NSMutableDictionary dictionary];
    if (fp16_) macros[@"JMT_FP16"] = @1;
    if (mpp) {
      if (@available(macOS 26.0, iOS 26.0, *)) {
        macros[@"JMT_MPP"] = @1;
        options.languageVersion = MTLLanguageVersion4_0;
      } else {
        return false;
      }
    }
    options.preprocessorMacros = macros;
    NSError* error = nil;
    id<MTLLibrary> library = [device_ newLibraryWithSource:@(kJmtMetalSource) options:options error:&error];
    if (!library) {
      error_ = describe_error(error);
      if (mpp && profile_) std::fprintf(stderr, "jmt metal: Metal Performance Primitives not available: %s\n", error_.c_str());
      return false;
    }
    library_ = library;
    pipelines_.clear();
    if (!mpp) return true;
    try {
      // One SIMD group must be 32 threads: the tiles of k_attn and k_layer_norm_sg are sized for that.
      for (const char* name : {"k_mm", "k_attn", "k_layer_norm_sg", "k_readout", "k_preprocess"})
        if (pipeline(name).threadExecutionWidth != 32) return false;
    } catch (const std::exception& e) {
      error_ = e.what();
      return false;
    }
    return true;
  }

  void report() const {
    double total = 0;
    std::map<std::string, Stat> by_kernel;
    std::vector<std::pair<std::string, Stat>> rows(stats_.begin(), stats_.end());
    for (const auto& r : rows) {
      total += r.second.ms;
      std::string kernel = r.first.substr(r.first.rfind(' ') + 1);
      by_kernel[kernel].ms += r.second.ms;
      by_kernel[kernel].calls += r.second.calls;
    }
    auto print = [&](const char* title, std::vector<std::pair<std::string, Stat>> v) {
      std::sort(v.begin(), v.end(), [](const auto& a, const auto& b) { return a.second.ms > b.second.ms; });
      std::fprintf(stderr, "\n%-58s %10s %7s %6s\n", title, "ms", "share", "calls");
      for (size_t i = 0; i < v.size() && i < 40; ++i)
        std::fprintf(stderr, "%-58s %10.2f %6.1f%% %6ld\n", v[i].first.c_str(), v[i].second.ms,
                     total > 0 ? 100.0 * v[i].second.ms / total : 0.0, v[i].second.calls);
    };
    std::fprintf(stderr, "\njmt metal profile: GPU time %.1f ms, %ld buffers created, %s kernels\n", total, buffers_created_,
                 mpp_ ? "Metal Performance Primitives" : "plain");
    print("operation  kernel", rows);
    print("kernel", std::vector<std::pair<std::string, Stat>>(by_kernel.begin(), by_kernel.end()));
  }

  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, const View& v) { [enc setBuffer:v.buffer offset:0 atIndex:i]; }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, int v) { [enc setBytes:&v length:sizeof(v) atIndex:i]; }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, float v) { [enc setBytes:&v length:sizeof(v) atIndex:i]; }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, const Float3& v) { [enc setBytes:&v length:sizeof(v) atIndex:i]; }

  id<MTLComputeCommandEncoder> encoder() {
    if (!command_) {
      command_ = [queue_ commandBuffer];
      if (!command_) fail("cannot create a command buffer");
      encoder_ = [command_ computeCommandEncoderWithDispatchType:MTLDispatchTypeSerial];
    }
    return encoder_;
  }

  id<MTLComputePipelineState> pipeline(const std::string& name) {
    auto it = pipelines_.find(name);
    if (it != pipelines_.end()) return it->second;
    id<MTLFunction> fn = [library_ newFunctionWithName:@(name.c_str())];
    if (!fn) fail("kernel " + name + " not found");
    NSError* error = nil;
    id<MTLComputePipelineState> p = [device_ newComputePipelineStateWithFunction:fn error:&error];
    if (!p) fail("cannot create pipeline " + name + ": " + describe_error(error));
    pipelines_[name] = p;
    return p;
  }

  id<MTLDevice> device_;
  id<MTLCommandQueue> queue_;
  id<MTLLibrary> library_;
  std::map<std::string, id<MTLComputePipelineState>> pipelines_;
  std::map<std::pair<const float*, int>, id<MTLBuffer>> params_;
  bool fp16_ = false, mpp_ = false;
  std::string error_;
  long buffers_created_ = 0;
  id<MTLCommandBuffer> command_ = nil;
  id<MTLComputeCommandEncoder> encoder_ = nil;
  std::vector<id<MTLCommandBuffer>> submitted_;  // committed, numbers base_ .. epoch_ - 1
  long epoch_ = 0, base_ = 0, checked_ = 0;
  std::multimap<size_t, id<MTLBuffer>> free_, pending_;
  bool profile_ = false;
  std::string tag_, key_;
  std::map<std::string, Stat> stats_;
};
using ContextPtr = std::shared_ptr<Context>;

// A block of bytes from the pool, returned to it on destruction.
class Buffer {
 public:
  Buffer(const ContextPtr& ctx, size_t bytes, bool host = false) : ctx_(ctx), bytes_(bytes), b_(ctx->alloc(bytes, host)) {}
  ~Buffer() { ctx_->release(b_, bytes_); }
  Buffer(const Buffer&) = delete;
  Buffer& operator=(const Buffer&) = delete;
  View view() const { return {b_}; }
  void* host() const { return [b_ contents]; }  // reading results: after Context::sync

 private:
  ContextPtr ctx_;
  size_t bytes_;
  id<MTLBuffer> b_;
};

// Elements are in the backend's storage type (float or half), or float when `f32` is set.
struct MetalTensor : Tensor {
  ContextPtr ctx;
  bool half;
  long epoch;  // command buffer that computes it
  Buffer buf;
  MetalTensor(const ContextPtr& ctx_, int h_, int w_, int c_, bool host = false, bool f32 = false)
      : ctx(ctx_), half(ctx_->fp16() && !f32),
        buf(ctx_, static_cast<size_t>(h_) * w_ * c_ * (half ? sizeof(uint16_t) : sizeof(float)), host) {
    h = h_, w = w_, c = c_;
    epoch = ctx_->epoch();
  }
  void read(float* dst) const override {
    ctx->wait(epoch);
    const size_t count = size();
    if (half) {
      const uint16_t* src = static_cast<const uint16_t*>(buf.host());
      for (size_t i = 0; i < count; ++i) dst[i] = half_to_float(src[i]);
    } else if (count) {
      std::memcpy(dst, buf.host(), count * sizeof(float));
    }
  }
  View d() const { return buf.view(); }
};
using MetalPtr = std::shared_ptr<MetalTensor>;

const MetalTensor& dev(const TensorPtr& t) { return static_cast<const MetalTensor&>(*t); }

int checked(long long n) {
  if (n < 0 || n > INT_MAX) fail("tensor too large");
  return static_cast<int>(n);
}

class MetalOps : public Ops {
 public:
  MetalOps(int device, bool fp16) : ctx_(std::make_shared<Context>(device, fp16)) {
    const char* e = std::getenv("JMT_METAL_LINEAR");
    std::string lin = e && *e ? e : "r8_t4";
    if (std::sscanf(lin.c_str(), "r%d_t%d", &linear_rows_, &linear_tile_) != 2) fail("unknown JMT_METAL_LINEAR");
    linear_kernel_ = "k_linear_" + lin;
    if ((e = std::getenv("JMT_METAL_APPLY")) && std::sscanf(e, "r%d_t%d", &apply_rows_, &apply_tile_) != 2) fail("unknown JMT_METAL_APPLY");
    if ((e = std::getenv("JMT_METAL_ATTENTION_CHUNK"))) attention_chunk_ = std::atoi(e);
    threads_ = std::max(1u, std::thread::hardware_concurrency());
  }

  TensorPtr upload(const float* data, int h, int w, int c) override {
    auto out = std::make_shared<MetalTensor>(ctx_, h, w, c, true);
    ctx_->store(data, out->size(), out->buf.host());
    return out;
  }

  TensorPtr preprocess(const float* rgb, int height, int width, int out_h, int out_w, const float mean[3],
                       const float std[3]) override {
    std::vector<float> v(static_cast<size_t>(out_h) * out_w * 3);
    for (int y = 0; y < out_h; ++y)
      preprocess_row(rgb, height, width, out_h, out_w, mean, std, y, v.data() + static_cast<size_t>(y) * out_w * 3);
    return upload(v.data(), out_h, out_w, 3);
  }

  TensorPtr preprocess_u8(const unsigned char* data, int height, int width, int stride, int channels, int out_h,
                          int out_w, const float mean[3], const float std[3]) override {
    if (!ctx_->mpp()) return Ops::preprocess_u8(data, height, width, stride, channels, out_h, out_w, mean, std);
    const size_t bytes = static_cast<size_t>(height - 1) * stride + static_cast<size_t>(width) * channels;
    Buffer image(ctx_, (bytes + 4095) / 4096 * 4096, true);  // rounded up so images of similar size reuse it
    std::memcpy(image.host(), data, bytes);
    // Source rows and columns of the resize, computed here so they match the host implementation exactly.
    Buffer taps(ctx_, static_cast<size_t>(out_h + out_w) * 3 * sizeof(float), true);
    float* t = static_cast<float*>(taps.host());
    for (int i = 0; i < out_h + out_w; ++i, t += 3) {
      int i0, i1;
      if (i < out_h) resize_source(i, out_h, height, &i0, &i1, t + 2);
      else resize_source(i - out_h, out_w, width, &i0, &i1, t + 2);
      t[0] = static_cast<float>(i0), t[1] = static_cast<float>(i1);
    }
    auto out = std::make_shared<MetalTensor>(ctx_, out_h, out_w, 3);
    ctx_->tag("preprocess");
    ctx_->run("k_preprocess", static_cast<long long>(out_h) * out_w, image.view(), taps.view(), stride, channels, out_h, out_w,
              Float3{{mean[0], mean[1], mean[2], 0}}, Float3{{std[0], std[1], std[2], 0}}, out->d());
    return out;
  }

  TensorPtr linear(const TensorPtr& xp, const Param& weight, const Param* bias) override {
    if (ctx_->mpp()) return linear_fused(xp, weight, bias, Act::None, nullptr);
    const MetalTensor& x = dev(xp);
    const int out_c = weight.shape[0], in_c = weight.shape[1];
    if (weight.shape.size() != 2 || in_c != x.c) fail("linear: shape mismatch");
    const int cpad = padded(out_c, linear_tile_);
    View w = ctx_->param(weight, linear_tile_, static_cast<size_t>(in_c) * cpad, [&](float* dst) {
      for (int o = 0; o < out_c; ++o)
        for (int i = 0; i < in_c; ++i) dst[slot(o, i, in_c)] = weight.data[static_cast<size_t>(o) * in_c + i];
    });
    ctx_->tag(format("linear %d -> %d, n %d", in_c, out_c, x.n()));
    return product(linear_kernel_, linear_rows_, linear_tile_, x.d(), x.h, x.w, in_c, w, bias, out_c, 1.0f, false);
  }

  TensorPtr linear_fused(const TensorPtr& xp, const Param& weight, const Param* bias, Act act,
                         const TensorPtr& residual) override {
    if (!ctx_->mpp()) return Ops::linear_fused(xp, weight, bias, act, residual);
    const MetalTensor& x = dev(xp);
    const int out_c = weight.shape[0], in_c = weight.shape[1];
    if (weight.shape.size() != 2 || in_c != x.c) fail("linear: shape mismatch");
    if (residual && (residual->n() != x.n() || residual->c != out_c)) fail("linear: residual shape mismatch");
    ctx_->tag(format("linear %d -> %d, n %d", in_c, out_c, x.n()));
    return mm(x.d(), x.h, x.w, in_c, stored(weight), bias, out_c, act, residual);
  }

  TensorPtr conv(const TensorPtr& xp, const Param& weight, const Param& bias, int k, int stride, int pad) override {
    const MetalTensor& x = dev(xp);
    const int out_c = weight.shape[0], in_c = weight.shape[1];
    if (weight.shape.size() != 4 || in_c != x.c || weight.shape[2] != k) fail("conv: shape mismatch");
    const int oh = (x.h + 2 * pad - k) / stride + 1, ow = (x.w + 2 * pad - k) / stride + 1, cols = k * k * in_c;
    auto patches = std::make_shared<MetalTensor>(ctx_, oh, ow, cols);
    ctx_->tag(format("conv%d c%d -> %d, %dx%d", k, in_c, out_c, ow, oh));
    ctx_->run("k_patches", static_cast<long long>(patches->size()), x.d(), x.h, x.w, x.c, k, stride, pad, oh, ow, patches->d());
    if (ctx_->mpp()) {
      // (out, in, k, k) -> (out, k * k * in), columns ordered as the patches: (ky, kx, channel).
      View w = ctx_->param(weight, kPatchOrder, static_cast<size_t>(out_c) * cols, [&](float* dst) {
        for (int o = 0; o < out_c; ++o)
          for (int ch = 0; ch < in_c; ++ch)
            for (int t = 0; t < k * k; ++t)
              dst[static_cast<size_t>(o) * cols + t * in_c + ch] = weight.data[(static_cast<size_t>(o) * in_c + ch) * k * k + t];
      });
      return mm(patches->d(), oh, ow, cols, w, &bias, out_c, Act::None, nullptr);
    }
    const int cpad = padded(out_c, linear_tile_);
    View w = ctx_->param(weight, linear_tile_, static_cast<size_t>(cols) * cpad, [&](float* dst) {
      for (int o = 0; o < out_c; ++o)
        for (int ch = 0; ch < in_c; ++ch)
          for (int t = 0; t < k * k; ++t)
            dst[slot(o, t * in_c + ch, cols)] = weight.data[(static_cast<size_t>(o) * in_c + ch) * k * k + t];
    });
    return product(linear_kernel_, linear_rows_, linear_tile_, patches->d(), oh, ow, cols, w, &bias, out_c, 1.0f, false);
  }

  TensorPtr dwconv7(const TensorPtr& xp, const Param& weight, const Param& bias) override {
    const MetalTensor& x = dev(xp);
    const int c = x.c;
    if (c % 4 != 0) fail("dwconv7: channels must be a multiple of 4");
    View taps = ctx_->param(weight, 0, static_cast<size_t>(49) * c, [&](float* dst) {
      for (int ch = 0; ch < c; ++ch)
        for (int t = 0; t < 49; ++t) dst[static_cast<size_t>(t) * c + ch] = weight.data[static_cast<size_t>(ch) * 49 + t];
    });
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, c);
    ctx_->tag(format("dwconv7 c%d %dx%d", c, x.w, x.h));
    ctx_->run("k_dwconv7", static_cast<long long>(x.n()) * (c / 4), x.d(), taps, vec(bias), x.h, x.w, c, out->d());
    return out;
  }

  TensorPtr layer_norm_act(const TensorPtr& xp, const Param& gain, const Param& bias, float eps, Act act) override {
    const MetalTensor& x = dev(xp);
    const int g = static_cast<int>(gain.size());
    if (!ctx_->mpp() || g % 32 != 0 || g > 1024) return Ops::layer_norm_act(xp, gain, bias, eps, act);
    if (g <= 0 || x.c % g != 0) fail("layer_norm: shape mismatch");
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, x.c);
    ctx_->tag(format("layer_norm c%d g%d n %d", x.c, g, x.n()));
    ctx_->run_groups("k_layer_norm_sg", static_cast<long long>(x.n()) * (x.c / g), 32, x.d(), vec(gain), vec(bias), x.n(), x.c, g,
                     eps, act_code(act), out->d());
    return out;
  }

  TensorPtr layer_norm(const TensorPtr& xp, const Param& gain, const Param& bias, float eps) override {
    const MetalTensor& x = dev(xp);
    const int g = static_cast<int>(gain.size());
    if (ctx_->mpp() && g % 32 == 0 && g <= 1024) return layer_norm_act(xp, gain, bias, eps, Act::None);
    if (g <= 0 || x.c % g != 0) fail("layer_norm: shape mismatch");
    auto out = std::make_shared<MetalTensor>(ctx_, x.h, x.w, x.c);
    ctx_->tag(format("layer_norm c%d g%d n %d", x.c, g, x.n()));
    ctx_->run("k_layer_norm", static_cast<long long>(x.n()) * (x.c / g), x.d(), vec(gain), vec(bias), x.n(), x.c, g, eps, out->d());
    return out;
  }

  TensorPtr gelu(const TensorPtr& xp) override { return unary(xp, kGelu, "gelu"); }
  TensorPtr relu(const TensorPtr& xp) override { return unary(xp, kRelu, "relu"); }


// Metal backend: host side. The kernels are in kernels.metal.
//
// Every buffer uses shared storage, so the host reads results and writes inputs in place. Operations are
// encoded into one command buffer, which is committed and waited for only when the host needs a value
// (Tensor::read, the read-out). The shader source is compiled at run time.
//
// Precision: FP32 by default. In FP16 mode the kernels are compiled with JMT_FP16: tensors and weights are
// stored as half, arithmetic stays float. The logits of the read-out are float in both modes.
//
// Not on the GPU yet: image preprocessing (512 x 512 x 3 values) and the read-out's selection of the 512
// largest logits per query, which runs on host threads from logits computed on the GPU.
//
// Environment: JMT_METAL_PROFILE=1 runs every dispatch in its own command buffer and prints GPU time per
// operation when the backend is destroyed. JMT_METAL_LINEAR picks the matrix-product kernel (r1_t8, r2_t8,
// r4_t8, r8_t4, r4_t16, r8_t8) and JMT_METAL_APPLY the attention value product (r4_t8, r2_t16), for tuning.

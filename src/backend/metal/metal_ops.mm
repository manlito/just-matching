    ctx_->tag("add");
    ctx_->run("k_add", checked(a.size()), a.d(), b.d(), checked(a.size()), out->d());
    return out;
  }

  TensorPtr concat(const TensorPtr& ap, const TensorPtr& bp) override {
    const MetalTensor &a = dev(ap), &b = dev(bp);
    if (a.n() != b.n()) fail("concat: shape mismatch");
    auto out = std::make_shared<MetalTensor>(ctx_, a.h, a.w, a.c + b.c);
    ctx_->tag("concat");
    ctx_->run("k_copy_channels", static_cast<long long>(a.n()) * a.c, a.d(), a.n(), a.c, 0, a.c, 0, out->c, out->d());
    ctx_->run("k_copy_channels", static_cast<long long>(b.n()) * b.c, b.d(), b.n(), b.c, 0, b.c, a.c, out->c, out->d());
    return out;
  }


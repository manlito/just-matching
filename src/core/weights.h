// Reader/writer for the tensor container (.jmtw weights, .jmtt tensors; the just-keypoints format). See tools/jmtfile.py.
#pragma once

#include <cstddef>
#include <cstdint>
#include <deque>
#include <map>
#include <string>
#include <vector>

namespace jmt {

// A float32 tensor that lives inside a loaded container (float16 tensors are widened to float32 on load).
struct Param {
  std::vector<int> shape;
  const float* data = nullptr;
  size_t size() const {
    size_t n = 1;
    for (int d : shape) n *= static_cast<size_t>(d);
    return n;
  }
};

// A float32 tensor with its own storage, for Weights::from_tensors.
struct OwnedTensor {
  std::string name;
  std::vector<int> shape;
  std::vector<float> data;
};

class Weights {
 public:
  // Both throw std::runtime_error on malformed input. The blob is copied. Besides the container, both read
  // FlexGlue's and LightGlue's PyTorch checkpoints (flexglue.pth, *_lightglue.pth; see checkpoint.h).
  static Weights from_memory(const void* data, size_t size);
  static Weights from_file(const std::string& path);
  // Takes the tensors over.
  static Weights from_tensors(std::map<std::string, std::string> meta, std::vector<OwnedTensor> tensors);

  const Param& get(const std::string& name) const;       // throws if missing
  const Param* find(const std::string& name) const;      // nullptr if missing
  const std::string& meta(const std::string& key) const; // throws if missing
  std::vector<std::string> names() const;                 // every tensor, sorted
  int meta_int(const std::string& key) const;
  const std::map<std::string, std::string>& metadata() const { return meta_; }

 private:
  std::vector<uint32_t> storage_;  // 4-byte aligned copy of the file
  std::deque<std::vector<float>> widened_;  // float16 tensors as float32
  std::map<std::string, Param> tensors_;
  std::map<std::string, std::string> meta_;
};

// Tensor to be written by write_container, given as float32.
struct NamedTensor {
  std::string name;
  std::vector<int> shape;
  const float* data;
};
// fp16: store every tensor as float16 (rounded to nearest, ties to even, as numpy's astype), as
// tools/export_weights.py --fp16 does.
void write_container(const std::string& path, const std::map<std::string, std::string>& meta,
                     const std::vector<NamedTensor>& tensors, bool fp16 = false);

// Weights built into the library (JMT_EMBED_WEIGHTS; generated by cmake/embed.cmake): the .jmtw file of
// `model`, e.g. "lightglue-aliked". False when that model was not built in.
bool embedded_weights(const std::string& model, const void** data, size_t* size);


}  // namespace jmt
